import { describe, expect, it } from 'vitest'
import { findCity, isCityOnly } from './cities.ts'

describe('findCity', () => {
  it.each([
    ['Фотограф Олег, Тула', 'Тула'],
    ['Барбершоп в Туле, ул. Садовая, 5', 'Тула'],
    ['Принимаю в Самаре', 'Самара'],
    ['Работаю из Тулы', 'Тула'],
    ['Салон в Перми', 'Пермь'],
    ['Студия в Казани', 'Казань'],
    ['Кофейня в Твери', 'Тверь'],
    ['Маникюр в Сочи', 'Сочи'],
    ['Студия в Омске', 'Омск'],
    ['Мастер в спб', 'Санкт-Петербург'],
    ['Мастер в Санкт-Петербурге', 'Санкт-Петербург'],
    ['Салон в мск', 'Москва'],
    ['Студия в Ростове-на-Дону', 'Ростов-на-Дону'],
  ])('«%s» → %s', (description, city) => expect(findCity(description)).toBe(city))

  it.each([
    'Тулуп на заказ, пошив',
    'Работаю в студии, ул. Кирова, 5',
    'Репетитор по математике',
    'Мастер из Нижнего Тагила',
    'Салон в Ростове Великом',
    'Владимир, барбер',
    'Из Москвы в Тулу, доставка',
    'Улица Тверская, 5',
    'Москвич, ремонт',
  ])('«%s» → не угадываем', (description) => expect(findCity(description)).toBeNull())
})

describe('isCityOnly', () => {
  it('только название города в любой форме', () => {
    expect(isCityOnly('Тула', 'Тула')).toBe(true)
    expect(isCityOnly('Туле', 'Тула')).toBe(true)
    expect(isCityOnly('Фотограф в Туле', 'Тула')).toBe(false)
    expect(isCityOnly('Самара', 'Тула')).toBe(false)
    expect(isCityOnly('', 'Тула')).toBe(false)
  })
})

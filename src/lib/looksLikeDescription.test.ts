import { describe, expect, it } from 'vitest'
import { looksLikeDescription } from './looksLikeDescription'

describe('looksLikeDescription: в поле названия вписали описание бизнеса', () => {
  it.each([
    'Барбершоп «Борода»',
    'Маникюр у Юли',
    'Репетитор по английскому, Казань',
    'Фотограф Анна Белова',
    'Fade Room',
    '',
  ])('название — без подсказки: %s', (text) => {
    expect(looksLikeDescription(text)).toBe(false)
  })

  it.each([
    ['цена', 'Стрижка 1500 ₽'],
    ['цена «р»', 'маникюр 1600р'],
    ['цена «к»', 'свадьба от 25к'],
    ['телефон', 'Борода +7 999 123-45-67'],
    ['телефон через 8', 'звоните 8-922-604-18-37'],
    ['иностранный телефон', 'WhatsApp +375 29 614-27-83'],
    ['ник', 'пишите @barber_ivan'],
    ['две фразы', 'Стригу дома. Детская стрижка тоже'],
    ['длинный текст', 'Барбершоп в Самаре на улице Ленина рядом с остановкой, работаем каждый день'],
    ['перечисление', 'стрижка, борода, укладка, камуфляж седины'],
  ])('описание (%s) — подсказка', (_, text) => {
    expect(looksLikeDescription(text)).toBe(true)
  })
})
